import test from "node:test";
import assert from "node:assert/strict";
import Database from "better-sqlite3";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { collectTrajectories, collectDiagnosticMetrics, AUDIT_SINCE, AUDIT_UNTIL, SAFE_PROJECTION, intervalUnion } from "./trajectory-audit.js";

test("audit timezone, overlap, ongoing, malformed, usage, privacy and readonly fixtures", (t) => {
  const root = mkdtempSync(join(tmpdir(), "quaymesh-audit-")), path = join(root, "fixture.sqlite");
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const db = new Database(path);
  db.exec(`create table console_work_runs(id,project_id,status,acceptance,created_at,finished_at,origin,summary);
    create table console_operations(run_id,kind,status,created_at,finished_at,evidence);
    create table console_executions(run_id,status,usage_quality,created_at,finished_at,delta);`);
  const insert = db.prepare("insert into console_work_runs values(?,?,?,?,?,?,?,?)");
  const origin = JSON.stringify({ entryPoint: "chatgpt_mcp", conversationHash: "a".repeat(24), title: "SECRET" });
  insert.run("old", "project", "running", "pending", "2026-09-06T00:00:00Z", null, origin, "SECRET");
  insert.run("boundary", "project", "completed", "passed", "2026-09-07T00:00:00+08:00", "2026-09-07T02:00:00+08:00", origin, "SECRET");
  insert.run("excluded", "project", "running", "pending", AUDIT_UNTIL, null, origin, "SECRET");
  insert.run("ended-at-start", "project", "completed", "passed", "2026-09-06T00:00:00Z", AUDIT_SINCE, origin, "SECRET");
  insert.run("bad-time", "project", "failed", "failed", "garbage", null, origin, "SECRET");
  insert.run("other", "project", "running", "pending", AUDIT_SINCE, null, '{"entryPoint":"other_mcp"}', "SECRET");
  insert.run("bad-origin", "project", "SECRET", "SECRET", AUDIT_SINCE, null, '{', "SECRET");
  const op = db.prepare("insert into console_operations values(?,?,?,?,?,?)");
  op.run("boundary", "command", "completed", AUDIT_SINCE, "2026-09-06T17:00:00Z", "SECRET");
  op.run("boundary", "command", "failed", "2026-09-06T16:30:00Z", "2026-09-06T17:30:00Z", "SECRET");
  op.run("old", "command", "running", AUDIT_SINCE, null, "SECRET");
  const ex = db.prepare("insert into console_executions values(?,?,?,?,?,?)");
  ex.run("boundary", "completed", "complete", AUDIT_SINCE, "2026-09-06T17:00:00Z", '{"totalTokens":42,"secret":"SECRET"}');
  ex.run("old", "running", "unavailable", AUDIT_SINCE, null, null);
  ex.run("other", "failed", "partial", AUDIT_SINCE, "2026-09-06T17:00:00Z", '{');
  db.close();
  const before = readFileSync(path);
  const result = collectTrajectories(path, { since: AUDIT_SINCE, until: AUDIT_UNTIL });
  assert.deepEqual(readFileSync(path), before);
  assert.equal(result.coverage.selectedRuns, 4);
  assert.equal(result.coverage.malformedRecords, 1);
  const parent = result.conversations.find((g) => g.association.startsWith("parent:"))!;
  assert.equal(parent.runs, 2); assert.equal(parent.knownDeltaTokens, 42); assert.equal(parent.missingDeltaExecutions, 1);
  assert.equal(parent.endedDurations.sumMs, 7_200_000); assert.equal(parent.endedUnionWallMsInWindow, 5_400_000);
  assert.equal(parent.activeElapsedAtCollection.count, 1);
  assert.equal(parent.operationsByKind.command?.failed, 1);
  assert.equal(result.conversations.find((g) => g.association === "unassociated_other_mcp")?.runs, 1);
  assert(!JSON.stringify(result).includes("SECRET"));
  assert(!JSON.stringify(SAFE_PROJECTION).match(/summary|evidence|title|select \*/));
  assert.equal(collectTrajectories(path, { since: AUDIT_SINCE, until: AUDIT_UNTIL, selection: "created" }).coverage.selectedRuns, 3);
  assert(collectTrajectories(path, { since: AUDIT_SINCE, until: AUDIT_UNTIL, maxRows: 1 }).coverage.truncated);
  assert.throws(() => collectTrajectories(join(root, "missing"), { since: AUDIT_SINCE, until: AUDIT_UNTIL }));
  assert.throws(() => collectTrajectories(path, { since: "2026-09-07", until: AUDIT_UNTIL }));
  assert.equal(intervalUnion([[1, 5], [2, 3], [4, 6]]), 5);
});

test("diagnostic stream emits only fixed event/code metrics and bounds malformed/long/truncated input", (t) => {
  const root = mkdtempSync(join(tmpdir(), "quaymesh-audit-log-")), path = join(root, "fixture.jsonl");
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const row = { ts: AUDIT_SINCE, event: "process_start_failed", errorCode: "ENOENT", command: "SECRET" };
  writeFileSync(path, [JSON.stringify(row), JSON.stringify({ ...row, event: "SECRET", errorCode: "SECRET" }), "{", "x".repeat(2000), JSON.stringify({ ...row, ts: AUDIT_UNTIL })].join("\n") + "\n");
  const result = collectDiagnosticMetrics(path, AUDIT_SINCE, AUDIT_UNTIL, { maxLineBytes: 1000 });
  assert.equal(result.inWindow, 2); assert.equal(result.overlong, 1); assert.equal(result.malformed, 1);
  assert.equal(result.events?.process_start_failed, 1); assert.equal(result.codes?.ENOENT, 1);
  assert(!JSON.stringify(result).includes("SECRET"));
  assert(collectDiagnosticMetrics(path, AUDIT_SINCE, AUDIT_UNTIL, { maxBytes: 10 }).truncated);
  assert(collectDiagnosticMetrics(path, AUDIT_SINCE, AUDIT_UNTIL, { maxLines: 1 }).truncated);
});
